"""أداة الوقت الموحد لتسجيل أحداث رحلة مراقبة السيرفر.

يضمن هذا الملف أن التقارير والمهام والأدلة تستخدم وقت UTC نفسه، فلا تختلط
الأحداث عند مقارنة فحص السيرفر بتحليل أو معالجة حدثت في منطقة زمنية أخرى."""
from datetime import UTC, datetime


def utc_now() -> datetime:
    """
    يعيد الوقت الحالي بتنسيق UTC لتثبيت ترتيب أحداث النظام.

    تستخدمه السجلات والتقارير وحالات التحقيق كمرجع زمني مشترك يمكن مقارنته
    مهما كان موقع السيرفر أو المستخدم.
    """
    return datetime.now(UTC)

"""تهيئة سجل الأحداث الذي يشرح ما يحدث أثناء تشغيل التطبيق.

توحّد هذه الوحدة مستوى التسجيل وشكله حتى يمكن تتبع بدء المراقبة وفشلها وحالة
التحليل والمعالجة من دون إضافة إعداد تسجيل مختلف في كل خدمة."""
import logging


def configure_logging(
    level: int = logging.INFO,
) -> None:
    """
    يهيئ التسجيل بمستوى وشكل موحدين لكل مراحل التطبيق.

    يسمح المستوى بزيادة التفاصيل أثناء التشخيص، بينما يضيف الشكل وقت الحدث
    ومستواه واسم مصدره لتسهيل ربط السجل بالتقرير أو المهمة المناسبة.
    """
    logging.basicConfig(
        level=level,
        format=(
            "%(asctime)s | %(levelname)s | "
            "%(name)s | %(message)s"
        ),
    )
